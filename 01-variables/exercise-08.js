const adultPrice = 2000;
const childPrice = 1000;
const adultTickets = 2;
const childTickets = 3;

const adultTotal = adultPrice * adultTickets;
const childTotal = childPrice * childTickets;

const total = adultTotal + childTotal;

console.log(`Adult tickets: ${adultTickets}`);
console.log(`Adult total: ${adultTotal}`);
console.log(`Child tickets: ${childTickets}`);
console.log(`Child total: ${childTotal}`);
console.log(`Total: ${total}`);
